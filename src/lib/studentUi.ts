type StudentCopy = (typeof copy)['es']

const FALLBACK: Record<string, keyof typeof copy> = {
  es: 'es',
  en: 'en',
  pt: 'es',
  it: 'es',
  de: 'en',
}

export function studentCopy(lang: AppLanguageCode | undefined): StudentCopy {
  const key = FALLBACK[lang || 'es'] ?? 'es'
  return copy[key]
}
