import type { AppLanguageCode } from '../types'

export const APP_LANG_OPTIONS: { code: AppLanguageCode; label: string }[] = [
  { code: 'es', label: 'Español' },
  { code: 'en', label: 'English' },
  { code: 'pt', label: 'Português' },
  { code: 'it', label: 'Italiano' },
  { code: 'de', label: 'Deutsch' },
]

export function parseAppLanguage(value: unknown): AppLanguageCode {
  const code = String(value || 'es')
  return APP_LANG_OPTIONS.some((l) => l.code === code) ? (code as AppLanguageCode) : 'es'
}

